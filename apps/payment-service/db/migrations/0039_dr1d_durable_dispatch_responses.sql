-- 0039 — payment-service: durable refund dispatch sends, responses and their exactly-once application (Core V2 D-R1D / OD-DR1-6; the Owner's
-- conditional GO of 2026-11-28 and Q1, Q2 of 2026-11-24). DEVELOPMENT AND SIMULATION ONLY. EVIDENCE ONLY: expand only. No refund, dispatch,
-- replacement, finality-eligibility, allocation, case, hold or release rule changes; no existing row is rewritten; nothing is backfilled; nothing purged.
--
--   * `refund_dispatch_send`: one row per provider send of an attempt's key, durable BEFORE the call. It never proves the provider received the call.
--       - `first_send`: written in the transaction that commits `authorized` -> `dispatching` (the attempt's first send; at most one per attempt).
--       - `same_key_resend`: a send the existing D-R1A rule permits (certified retention), while the attempt is `dispatching` or `unknown`.
--     The provider, payment and key (= attempt id) must be the attempt's own; the send number and time are derived by the database.
--   * `refund_dispatch_observation`: the provider's answer to ONE send, written in its own transaction after the call and before any decision.
--     One per send (a repeated write of the same answer is idempotent; nothing overwrites it); distinct sends keep distinct observations. The digest
--     and time are derived by the database. A send with no observation is an UNKNOWN outcome (a crash or a database outage after the call).
--   * `refund_dispatch_application`: the exactly-once effect of one observation on its attempt, written under the payment and attempt row locks in the
--     transaction that applies it: `transitioned` (to the status its classification names), `preserved_contradiction` (D-R1A) or `no_effect`.
--     "appliedBy" (`dispatch` | `recovery`) is the producer's label; "attemptStatusAfter" must be the attempt's status at that point.
--   * `refund_attempt_failure_finality` (0037) gains "dispatchObservationId": a NEW `dispatch_response` finality must name this attempt's own rejected
--     observation with the same code, and at commit that observation must have been applied, by the dispatch, as the transition to `failed`. Recovery
--     therefore never records finality (Q1): the certificate, fingerprint, revocation and evidence rules of 0037 stay as they are and still apply.
--   * Privileges: the runtime role may INSERT and SELECT the three tables, nothing else; append-only for every role. A superuser can bypass triggers.

CREATE TABLE refund_dispatch_send (
  id                  uuid PRIMARY KEY,              -- generated by the worker before the call: the correlation identity of the send
  "refundAttemptId"   uuid NOT NULL,
  "paymentId"         uuid NOT NULL,
  provider            text NOT NULL,
  "idempotencyKey"    text NOT NULL,
  "sendNumber"        integer NOT NULL,              -- derived: 1 + the attempt's highest, under the attempt row lock
  purpose             text NOT NULL,
  "createdAt"         timestamptz NOT NULL,          -- derived: database time
  CONSTRAINT refund_dispatch_send_attempt FOREIGN KEY ("refundAttemptId", "paymentId") REFERENCES refund_attempt (id, "paymentId"),
  CONSTRAINT refund_dispatch_send_number UNIQUE ("refundAttemptId", "sendNumber"),
  CONSTRAINT refund_dispatch_send_identity UNIQUE (id, "refundAttemptId"),
  CONSTRAINT refund_dispatch_send_key CHECK ("idempotencyKey" = "refundAttemptId"::text),
  CONSTRAINT refund_dispatch_send_purpose CHECK (purpose IN ('first_send', 'same_key_resend')),
  CONSTRAINT refund_dispatch_send_number_positive CHECK ("sendNumber" >= 1)
);
CREATE UNIQUE INDEX refund_dispatch_send_first_once ON refund_dispatch_send ("refundAttemptId") WHERE purpose = 'first_send';

CREATE TABLE refund_dispatch_observation (
  id                  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "sendId"            uuid NOT NULL,
  "refundAttemptId"   uuid NOT NULL,
  classification      text NOT NULL,
  "providerRefundId"  text,                          -- accepted only: the provider's refund reference
  "providerCode"      text,                          -- rejected only: the bounded failure code
  "responseDigest"    text NOT NULL,                 -- derived: sha256 of the canonical {classification, providerRefundId, providerCode}
  source              text NOT NULL DEFAULT 'dispatch_response',
  "observedAt"        timestamptz NOT NULL,          -- derived: database time
  CONSTRAINT refund_dispatch_observation_send FOREIGN KEY ("sendId", "refundAttemptId") REFERENCES refund_dispatch_send (id, "refundAttemptId"),
  CONSTRAINT refund_dispatch_observation_once UNIQUE ("sendId"),
  CONSTRAINT refund_dispatch_observation_identity UNIQUE (id, "refundAttemptId"),
  CONSTRAINT refund_dispatch_observation_classification CHECK (classification IN ('accepted', 'rejected', 'ambiguous', 'transport_error')),
  CONSTRAINT refund_dispatch_observation_reference CHECK ("providerRefundId" IS NULL OR char_length("providerRefundId") BETWEEN 1 AND 256),
  CONSTRAINT refund_dispatch_observation_code CHECK ("providerCode" IS NULL OR "providerCode" ~ '^[a-z][a-z0-9_]{0,63}$'),
  CONSTRAINT refund_dispatch_observation_shape CHECK ((classification = 'accepted') = ("providerRefundId" IS NOT NULL)
                                                  AND (classification = 'rejected') = ("providerCode" IS NOT NULL)),
  CONSTRAINT refund_dispatch_observation_digest CHECK ("responseDigest" ~ '^[0-9a-f]{64}$'),
  CONSTRAINT refund_dispatch_observation_source CHECK (source = 'dispatch_response')
);

CREATE TABLE refund_dispatch_application (
  "observationId"        uuid PRIMARY KEY,           -- once per observation
  "refundAttemptId"      uuid NOT NULL,
  effect                 text NOT NULL,
  "attemptStatusBefore"  text NOT NULL,
  "attemptStatusAfter"   text NOT NULL,              -- checked: the attempt's status when the application is written
  "appliedBy"            text NOT NULL,
  "appliedAt"            timestamptz NOT NULL,       -- derived: database time
  CONSTRAINT refund_dispatch_application_observation FOREIGN KEY ("observationId", "refundAttemptId") REFERENCES refund_dispatch_observation (id, "refundAttemptId"),
  CONSTRAINT refund_dispatch_application_effect CHECK (effect IN ('transitioned', 'preserved_contradiction', 'no_effect')),
  CONSTRAINT refund_dispatch_application_by CHECK ("appliedBy" IN ('dispatch', 'recovery')),
  CONSTRAINT refund_dispatch_application_shape CHECK ((effect = 'transitioned') = ("attemptStatusBefore" <> "attemptStatusAfter")
                                                  AND (effect <> 'transitioned' OR "attemptStatusBefore" IN ('dispatching', 'unknown')))
);
CREATE INDEX refund_dispatch_observation_attempt ON refund_dispatch_observation ("refundAttemptId");

-- ─────────────────────────────────────────────────────────────────────────────────────────────── guards

CREATE FUNCTION refund_dispatch_send_guard() RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE a refund_attempt%ROWTYPE; pay uuid;
BEGIN
  PERFORM refund_require_read_committed();
  SELECT "paymentId" INTO pay FROM refund_attempt WHERE id = NEW."refundAttemptId";
  PERFORM 1 FROM payment WHERE id = pay FOR UPDATE;                                   -- 0037's order: payment, then attempt
  SELECT * INTO a FROM refund_attempt WHERE id = NEW."refundAttemptId" FOR UPDATE;
  IF a.id IS NULL OR NEW."paymentId" IS DISTINCT FROM a."paymentId" OR NEW.provider IS DISTINCT FROM a.provider
     OR NEW."idempotencyKey" IS DISTINCT FROM a.id::text THEN
    RAISE EXCEPTION 'refund_dispatch_send: not the payment, provider and key of attempt %', NEW."refundAttemptId"
      USING ERRCODE = '23514', CONSTRAINT = 'refund_dispatch_send_binding';
  END IF;
  IF NOT (a.status = 'dispatching' OR (NEW.purpose = 'same_key_resend' AND a.status = 'unknown'))
     OR (NEW.purpose = 'first_send' AND EXISTS (SELECT 1 FROM refund_dispatch_send s WHERE s."refundAttemptId" = a.id)) THEN
    RAISE EXCEPTION 'refund_dispatch_send: attempt % (status %) may not record a % now', a.id, a.status, NEW.purpose
      USING ERRCODE = '23514', CONSTRAINT = 'refund_dispatch_send_state';
  END IF;
  NEW."sendNumber" := COALESCE((SELECT max(s."sendNumber") FROM refund_dispatch_send s WHERE s."refundAttemptId" = a.id), 0) + 1;
  NEW."createdAt" := clock_timestamp();
  RETURN NEW;
END $$;

CREATE FUNCTION refund_dispatch_observation_guard() RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog, public, pg_temp AS $$
BEGIN
  -- independent of the decision: no attempt lock, any attempt status (the answer arrives whatever happened meanwhile)
  NEW."responseDigest" := encode(sha256(convert_to(jsonb_build_object('classification', NEW.classification, 'providerRefundId', NEW."providerRefundId",
                            'providerCode', NEW."providerCode")::text, 'UTF8')), 'hex');
  NEW."observedAt" := clock_timestamp();
  RETURN NEW;
END $$;

CREATE FUNCTION refund_dispatch_application_guard() RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE a refund_attempt%ROWTYPE; pay uuid; o refund_dispatch_observation%ROWTYPE;
BEGIN
  PERFORM refund_require_read_committed();
  SELECT "paymentId" INTO pay FROM refund_attempt WHERE id = NEW."refundAttemptId";
  PERFORM 1 FROM payment WHERE id = pay FOR UPDATE;                                   -- re-entrant: the applying transaction already holds both
  SELECT * INTO a FROM refund_attempt WHERE id = NEW."refundAttemptId" FOR UPDATE;
  SELECT * INTO o FROM refund_dispatch_observation WHERE id = NEW."observationId" AND "refundAttemptId" = NEW."refundAttemptId";
  IF a.id IS NULL OR o.id IS NULL OR NEW."attemptStatusAfter" IS DISTINCT FROM a.status
     OR (NEW.effect = 'transitioned' AND NEW."attemptStatusAfter" IS DISTINCT FROM
           CASE o.classification WHEN 'accepted' THEN 'submitted' WHEN 'rejected' THEN 'failed' ELSE 'unknown' END) THEN
    RAISE EXCEPTION 'refund_dispatch_application: observation % does not leave attempt % in status %', NEW."observationId", NEW."refundAttemptId", NEW."attemptStatusAfter"
      USING ERRCODE = '23514', CONSTRAINT = 'refund_dispatch_application_state';
  END IF;
  NEW."appliedAt" := clock_timestamp();
  RETURN NEW;
END $$;

