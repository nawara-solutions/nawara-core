DO $$
DECLARE r record;
BEGIN
  REVOKE ALL ON refund_dispatch_send, refund_dispatch_observation, refund_dispatch_application FROM PUBLIC;
  FOR r IN
    SELECT c.relname AS tbl, a.grantee::regrole::text AS role, a.privilege_type AS priv
      FROM pg_class c, aclexplode(c.relacl) a
     WHERE c.relnamespace = 'public'::regnamespace AND a.grantee <> c.relowner AND a.grantee <> 0
       AND c.relname IN ('refund_dispatch_send', 'refund_dispatch_observation', 'refund_dispatch_application')
       AND a.privilege_type NOT IN ('SELECT', 'INSERT')
  LOOP
    EXECUTE format('REVOKE %s ON %I FROM %s', r.priv, r.tbl, r.role);
  END LOOP;
END $$;
